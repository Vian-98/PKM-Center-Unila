-- ============================================================================

-- FEEDBACKS (Kritik & Saran + pesan Kontak) -----------------------------------
-- Menggantikan tabel lama `feedbacks`.
CREATE TABLE IF NOT EXISTS feedbacks (
    id         BIGINT GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
    kind       VARCHAR(30) NOT NULL CHECK (kind IN ('saran', 'kontak')),
    name       VARCHAR(150),
    email      VARCHAR(255),
    message    TEXT NOT NULL,
    is_read    BOOLEAN NOT NULL DEFAULT FALSE,
    created_at TIMESTAMPTZ NOT NULL DEFAULT now()
);
CREATE INDEX IF NOT EXISTS idx_feedbacks_kind ON feedbacks (kind);

-- CONTACT_INFOS (baris tunggal id = 1) ----------------------------------------
-- Menggantikan tabel lama `contact_infos`.
CREATE TABLE IF NOT EXISTS contact_infos (
    id         BIGINT PRIMARY KEY DEFAULT 1 CHECK (id = 1),
    address    TEXT,
    email      VARCHAR(255),
    phone      VARCHAR(50),
    whatsapp   VARCHAR(50),
    instagram  VARCHAR(150),
    facebook   VARCHAR(150),
    map_embed  TEXT,
    updated_at TIMESTAMPTZ NOT NULL DEFAULT now()
);

-- ============================================================================
-- 10. VIEW: statistik usulan per skema (menggantikan tabel `scheme_stats`)
-- ============================================================================
-- Keputusan: statistik skema murni TURUNAN dari proposals — tidak ada tabel
-- `scheme_stats` dan tidak ada input manual. Endpoint admin terkait dihapus.
-- Statistik jumlah usulan kini dihitung dari PROPOSALS, bukan tabel tersendiri.
CREATE OR REPLACE VIEW v_scheme_stats AS
SELECT
    s.id     AS scheme_id,
    s.code   AS scheme,
    s.name   AS scheme_name,
    COUNT(p.id) FILTER (WHERE p.status <> 'draft') AS proposal_count,
    COUNT(p.id) FILTER (WHERE p.is_funded)         AS funded_count
FROM pkm_schemes s
LEFT JOIN proposals p ON p.scheme_id = s.id
GROUP BY s.id, s.code, s.name
ORDER BY s.id;

